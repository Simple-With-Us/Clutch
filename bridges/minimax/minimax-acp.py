#!/usr/bin/env python3
"""Clutch MiniMax ACP stdio bridge: the dsh engine with MiniMax as the model.

Stdout is JSON-RPC only.  Drives `dsh --profile <profile>` with MiniMax as
the LLM (same cordis tool loop as DeepSeek / dsh-acp.py).  Default profile
is `minimax-headless` — a full `@deepseek-ai/dsh-headless` stack with
`agent-default-model.provider: minimax`.  Override via CLUTCH_MINIMAX_PROFILE
env or `--profile` argv.

Engine state: DSH_HOME is always $CLUTCH_HOME/dsh (default ~/.clutch/dsh).
An inherited DSH_HOME is ignored, because vanilla dsh and BotFleet own ~/.dsh.

This is intentionally NOT the old HTTP-only chat/completions adapter.  That
path had no local tools and dropped image attachments, so Shellular MiniMax
behaved like the MiniMax chat web app.  Coding parity with DeepSeek means
spawning the dsh engine with MiniMax as the model.

Auth: process env `MINIMAX_API_KEY`, else `$DSH_HOME/.credentials.yaml`, else
`~/.secrets/global-api-keys` looked up by CLUTCH_MINIMAX_API_KEY_NAME — never
from agents.json.

Phone clients cannot answer interactive approvals.  Default
DSH_PERMISSION_MODE (an upstream-read name, so it is not renamed) is
danger-full-access (approval: never).

ACP wire contract (must match Shellular / @agentclientprotocol, same as
bridges/dsh/dsh-acp.py — do not regress to BotFleet content.delta / turn.*):
  - notifications: method `session/update` with
    `sessionUpdate: agent_message_chunk | agent_thought_chunk`
  - prompt result: `stopReason: endTurn`
  - image ACP blocks are materialized to files under the session cwd and
    the paths are appended to the text task so the coding agent can open them

Tracked copy: bridges/minimax/minimax-acp.py
Live install: ~/apps/clutch-runtime/bridges/minimax/minimax-acp.py (launcher: scripts/minimax-acp.sh)
"""

from __future__ import annotations

import datetime
import json
import os
import signal
import subprocess
import sys
import threading
import time
import uuid
from pathlib import Path
from typing import Any

_RUNTIME_ROOT = Path(
    os.environ.get("CLUTCH_RUNTIME_ROOT")
    or os.path.expanduser("~/apps/clutch-runtime"),
)
CLUTCH_HOME = os.environ.get("CLUTCH_HOME") or os.path.expanduser("~/.clutch")
ENGINE_BIN = os.environ.get("CLUTCH_BIN", str(_RUNTIME_ROOT / "node_modules/.bin/dsh"))
DSH_HOME = os.path.join(CLUTCH_HOME, "dsh")
ENGINE_PROFILE = os.environ.get("CLUTCH_MINIMAX_PROFILE", "minimax-headless")
DEFAULT_TIMEOUT_SEC = int(
    os.environ.get("CLUTCH_MINIMAX_ACP_TIMEOUT_SEC")
    or os.environ.get("CLUTCH_ACP_TIMEOUT_SEC", "900")
)
DEFAULT_HEARTBEAT_SEC = float(
    os.environ.get("CLUTCH_MINIMAX_ACP_HEARTBEAT_SEC")
    or os.environ.get("CLUTCH_ACP_HEARTBEAT_SEC", "5")
)
DEFAULT_PERMISSION_MODE = os.environ.get("DSH_PERMISSION_MODE", "danger-full-access")
MINIMAX_API_KEY_NAME = os.environ.get("CLUTCH_MINIMAX_API_KEY_NAME", "MINIMAX_API_KEY")

CLI_PATCH: str | None = None
for _idx, _arg in enumerate(sys.argv[1:]):
    if _arg == "--patch" and _idx + 1 < len(sys.argv[1:]):
        CLI_PATCH = sys.argv[1:][_idx + 1]
        break


def _write_temp_mcp_patch(servers: list[dict[str, Any]]) -> str | None:
    """Generate a cordis.patch.yml overlay loading @deepseek-ai/dsh-mcp-client for each MCP server."""
    if not servers:
        return None
    try:
        import tempfile
        import re
        td = tempfile.mkdtemp(prefix="clutch-mcp-")
        os.chmod(td, 0o700)
        patch_path = os.path.join(td, "cordis.patch.yml")
        lines = [
            "# Dynamic MCP servers overlay generated by the Clutch ACP bridge",
            "- insert:",
        ]
        used: set[str] = set()
        for idx, s in enumerate(servers):
            name = str(s.get("name") or f"mcp_{idx}")
            clean_name = re.sub(r"[^A-Za-z0-9_-]", "_", name)[:32]
            if not clean_name or clean_name in used:
                clean_name = f"mcp_{idx}_{clean_name}"[:32]
            used.add(clean_name)
            cmd = str(s.get("command") or "")
            args = [str(a) for a in s.get("args", [])] if isinstance(s.get("args"), list) else []
            env_list = s.get("env", []) if isinstance(s.get("env"), list) else []

            lines.append(f"    - id: clutch-mcp-{idx}-{clean_name}")
            lines.append("      name: '@deepseek-ai/dsh-mcp-client'")
            lines.append("      config:")
            lines.append(f"        serverName: {json.dumps(clean_name)}")
            lines.append("        transport: stdio")
            lines.append(f"        command: {json.dumps(cmd)}")
            if args:
                lines.append("        args:")
                for a in args:
                    lines.append(f"          - {json.dumps(a)}")
            else:
                lines.append("        args: []")
            if env_list:
                lines.append("        env:")
                for item in env_list:
                    if isinstance(item, dict) and "name" in item and "value" in item:
                        k = str(item["name"])
                        v = str(item["value"])
                        lines.append(f"          {k}: {json.dumps(v)}")
            else:
                lines.append("        env: {}")
            lines.append("        failOnStartupError: false")

        with open(patch_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        return patch_path
    except Exception:
        return None


def _cleanup_patch_file(patch_path: str | None) -> None:
    if not patch_path:
        return
    try:
        p = Path(patch_path)
        if p.is_file():
            p.unlink()
        if p.parent.is_dir() and p.parent.name.startswith("clutch-mcp-"):
            p.parent.rmdir()
    except OSError:
        pass


JsonDict = dict[str, Any]


def _load_minimax_key() -> None:
    """Ensure MINIMAX_API_KEY (or CLUTCH_MINIMAX_API_KEY_NAME) is in the process env.

    Order: already-set env → $DSH_HOME/.credentials.yaml → ~/.secrets/global-api-keys.
    Never prints or logs the value.
    """
    target = MINIMAX_API_KEY_NAME
    if os.environ.get(target) or os.environ.get("MINIMAX_API_KEY"):
        if not os.environ.get("MINIMAX_API_KEY") and os.environ.get(target):
            os.environ["MINIMAX_API_KEY"] = os.environ[target]
        return

    cred = Path(DSH_HOME) / ".credentials.yaml"
    if cred.is_file():
        try:
            raw_text = cred.read_text(encoding="utf-8", errors="replace")
        except OSError:
            raw_text = ""
        for raw in raw_text.splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if "MINIMAX_API_KEY" not in line and target not in line:
                continue
            if ":" in line:
                _k, val = line.split(":", 1)
            elif "=" in line:
                _k, val = line.split("=", 1)
            else:
                continue
            val = val.strip().strip("'").strip('"')
            if val:
                os.environ["MINIMAX_API_KEY"] = val
                os.environ[target] = val
                return

    secrets = Path.home() / ".secrets" / "global-api-keys"
    if not secrets.is_file():
        return
    try:
        raw_text = secrets.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return
    for raw in raw_text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, _, val = line.partition("=")
        if name.strip() not in {target, "MINIMAX_API_KEY"}:
            continue
        val = val.strip().strip("'").strip('"')
        if val:
            os.environ["MINIMAX_API_KEY"] = val
            os.environ[target] = val
            return


_load_minimax_key()

out_lock = threading.Lock()
sessions: dict[str, JsonDict] = {}
active_procs: dict[str, subprocess.Popen[str]] = {}
active_lock = threading.Lock()


def write(payload: JsonDict) -> None:
    raw = json.dumps(payload, ensure_ascii=True, separators=(",", ":")) + "\n"
    with out_lock:
        sys.stdout.write(raw)
        sys.stdout.flush()


def reply(req_id: Any, result: JsonDict) -> None:
    write({"jsonrpc": "2.0", "id": req_id, "result": result})


def fail(req_id: Any, message: str, code: int = -32000) -> None:
    write(
        {
            "jsonrpc": "2.0",
            "id": req_id,
            "error": {"code": code, "message": message},
        }
    )


def notify(method: str, params: JsonDict) -> None:
    write({"jsonrpc": "2.0", "method": method, "params": params})


def emit_text(session_id: str, text: str) -> None:
    if not text:
        return
    notify(
        "session/update",
        {
            "sessionId": session_id,
            "update": {
                "sessionUpdate": "agent_message_chunk",
                "content": {"type": "text", "text": text},
            },
        },
    )


def emit_thought(session_id: str, text: str) -> None:
    if not text:
        return
    notify(
        "session/update",
        {
            "sessionId": session_id,
            "update": {
                "sessionUpdate": "agent_thought_chunk",
                "content": {"type": "text", "text": text},
            },
        },
    )


def _materialize_image_block(item: dict[str, Any], dest_dir: Path, index: int) -> str | None:
    """Write one ACP image block to dest_dir; return absolute path or None."""
    import base64

    mime = ""
    data_b64 = ""
    if item.get("type") == "image":
        mime = str(item.get("mimeType") or item.get("mediaType") or "image/png")
        data_b64 = str(item.get("data") or "")
    elif item.get("type") == "resource" and isinstance(item.get("resource"), dict):
        res = item["resource"]
        mime = str(res.get("mimeType") or "")
        data_b64 = str(res.get("blob") or "")
        if not mime.startswith("image/"):
            return None
    else:
        return None
    if not data_b64:
        return None
    # Strip data-URL prefix if present
    if "," in data_b64 and data_b64.strip().lower().startswith("data:"):
        data_b64 = data_b64.split(",", 1)[1]
    try:
        raw = base64.b64decode(data_b64, validate=False)
    except Exception:
        return None
    if not raw:
        return None
    ext = {
        "image/png": ".png",
        "image/jpeg": ".jpg",
        "image/jpg": ".jpg",
        "image/webp": ".webp",
        "image/gif": ".gif",
    }.get(mime.lower(), ".bin")
    dest_dir.mkdir(parents=True, exist_ok=True)
    path = dest_dir / f"attachment-{index:02d}{ext}"
    path.write_bytes(raw)
    return str(path.resolve())


def extract_prompt_text(prompt: Any, cwd: str | None = None) -> str:
    """Flatten ACP prompt blocks to a text task for headless dsh.

    Image / resource image blocks are written under
    `<cwd>/.shellular-attachments/` (or /tmp) and their paths are appended
    so the coding agent can open them with local tools.
    """
    parts: list[str] = []
    image_paths: list[str] = []
    if isinstance(prompt, str):
        return prompt.strip()
    if not isinstance(prompt, list):
        return ""
    base = Path(cwd) if cwd and os.path.isdir(cwd) else Path("/tmp")
    dest = base / ".shellular-attachments"
    img_i = 0
    for item in prompt:
        if isinstance(item, str):
            parts.append(item)
            continue
        if not isinstance(item, dict):
            continue
        text = item.get("text")
        if text is None and isinstance(item.get("content"), str):
            text = item.get("content")
        if text:
            parts.append(str(text))
        path = _materialize_image_block(item, dest, img_i)
        if path:
            image_paths.append(path)
            img_i += 1
    body = "\n".join(parts).strip()
    if image_paths:
        note = (
            "Attached image file(s) saved on the local Mac "
            "(open with read/bash tools):\n"
            + "\n".join(f"- {p}" for p in image_paths)
        )
        body = f"{body}\n\n{note}" if body else note
    return body.strip()


def modes_block() -> JsonDict:
    return {
        "currentModeId": "agent",
        "availableModes": [
            {"id": "agent", "name": "Agent"},
        ],
    }


def _drain_stderr(proc: subprocess.Popen[str], session_id: str) -> None:
    stderr = proc.stderr
    if stderr is None:
        return
    try:
        for line in stderr:
            stripped = line.strip()
            if stripped:
                emit_text(session_id, f"[stderr] {stripped}\n")
    except (OSError, ValueError):
        pass


def _clear_active(session_id: str, proc: subprocess.Popen[str]) -> None:
    with active_lock:
        current = active_procs.get(session_id)
        if current is proc:
            active_procs.pop(session_id, None)


def _close_pipe(stream: Any) -> None:
    if stream is None:
        return
    try:
        stream.close()
    except (OSError, ValueError):
        pass


def _kill_proc_group(proc: subprocess.Popen[str]) -> None:
    pid = proc.pid
    if pid:
        try:
            os.killpg(pid, signal.SIGTERM)
        except (OSError, ProcessLookupError):
            try:
                proc.terminate()
            except OSError:
                pass
        try:
            proc.wait(timeout=3)
        except (subprocess.TimeoutExpired, OSError):
            try:
                os.killpg(pid, signal.SIGKILL)
            except (OSError, ProcessLookupError):
                try:
                    proc.kill()
                except OSError:
                    pass
    _close_pipe(proc.stdout)
    _close_pipe(proc.stderr)


def cancel_session(session_id: str) -> bool:
    with active_lock:
        proc = active_procs.get(session_id)
    if proc is not None:
        _kill_proc_group(proc)
    record = sessions.get(session_id)
    if record and record.get("patchFile"):
        _cleanup_patch_file(record["patchFile"])
    return proc is not None


def build_dsh_cmd(session_id: str, prompt_text: str) -> list[str]:
    cmd = [ENGINE_BIN, "--profile", ENGINE_PROFILE]
    patch = None
    if session_id in sessions and sessions[session_id].get("patchFile"):
        patch = sessions[session_id]["patchFile"]
    elif CLI_PATCH:
        patch = CLI_PATCH
    elif os.environ.get("CLUTCH_MINIMAX_PATCH") or os.environ.get("CLUTCH_PATCH"):
        patch = os.environ.get("CLUTCH_MINIMAX_PATCH") or os.environ.get("CLUTCH_PATCH")

    if patch and os.path.isfile(patch):
        cmd.extend(["--patch", patch])

    if session_id.startswith("session-"):
        cmd.extend(["--resume", session_id])
    cmd.append(prompt_text)
    return cmd


def handle_prompt(req_id: Any, session_id: str, prompt_text: str, cwd: str) -> None:
    env = os.environ.copy()
    env["DSH_HOME"] = DSH_HOME
    env.setdefault("DSH_PERMISSION_MODE", DEFAULT_PERMISSION_MODE)
    env["DSH_SESSION_ID"] = session_id
    env["CLUTCH_RESUME"] = session_id
    cmd = build_dsh_cmd(session_id, prompt_text)
    workdir = cwd if os.path.isdir(cwd) else None
    proc: subprocess.Popen[str] | None = None
    timed_out = False
    replied = False
    stdout_done = threading.Event()
    try:
        proc = subprocess.Popen(
            cmd,
            cwd=workdir,
            env=env,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            bufsize=1,
            start_new_session=True,
        )
        with active_lock:
            active_procs[session_id] = proc

        def read_stdout() -> None:
            try:
                stdout = proc.stdout
                if stdout is None:
                    return
                for line in stdout:
                    emit_text(session_id, line)
            except (OSError, ValueError):
                pass
            finally:
                stdout_done.set()

        stdout_thread = threading.Thread(target=read_stdout, daemon=True)
        stdout_thread.start()
        stderr_thread = threading.Thread(
            target=_drain_stderr,
            args=(proc, session_id),
            daemon=True,
        )
        stderr_thread.start()

        started = time.monotonic()
        heartbeat = max(DEFAULT_HEARTBEAT_SEC, 0.5)
        while not stdout_done.wait(timeout=heartbeat):
            elapsed = int(time.monotonic() - started)
            if elapsed >= DEFAULT_TIMEOUT_SEC:
                timed_out = True
                emit_text(
                    session_id,
                    f"\n[minimax-acp] Timed out after {DEFAULT_TIMEOUT_SEC}s.\n",
                )
                _kill_proc_group(proc)
                break
            marker = f"[working… {elapsed}s]\n"
            emit_thought(session_id, marker)

        stdout_thread.join(timeout=2)
        stderr_thread.join(timeout=2)
        if proc.poll() is None:
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                _kill_proc_group(proc)
        if timed_out:
            pass
        elif proc.returncode not in (0, None, -9, -15):
            emit_text(
                session_id,
                f"dsh (minimax) exited with code {proc.returncode}\n",
            )
        reply(req_id, {"stopReason": "endTurn"})
        replied = True
    except Exception as exc:
        emit_text(session_id, f"Execution error: {exc}\n")
        if not replied:
            reply(req_id, {"stopReason": "endTurn"})
            replied = True
    finally:
        if proc is not None:
            _clear_active(session_id, proc)
        if not replied:
            reply(req_id, {"stopReason": "endTurn"})


def list_dsh_sessions() -> list[JsonDict]:
    sess_root = Path(DSH_HOME) / "sessions"
    if not sess_root.is_dir():
        return []
    items: list[JsonDict] = []
    try:
        for dir_entry in sess_root.iterdir():
            if not dir_entry.is_dir() or dir_entry.name == "acp":
                continue
            raw_path = dir_entry.name.strip("-").replace("-", "/")
            cwd = "/" + raw_path if raw_path else str(Path.home())
            for sess_dir in dir_entry.iterdir():
                if not sess_dir.is_dir():
                    continue
                sess_id = sess_dir.name
                try:
                    mtime = sess_dir.stat().st_mtime
                    dt = datetime.datetime.fromtimestamp(
                        mtime,
                        tz=datetime.timezone.utc,
                    ).isoformat()
                except OSError:
                    dt = None
                repo_name = Path(cwd).name if Path(cwd).name else "DeepSeek"
                display_title = f"MiniMax/{repo_name}: {sess_id.replace('session-', '')[:8]}"
                items.append(
                    {
                        "sessionId": sess_id,
                        "cwd": cwd,
                        "title": display_title,
                        "updatedAt": dt,
                    }
                )
    except Exception:
        pass
    items.sort(key=lambda x: x.get("updatedAt") or "", reverse=True)
    return items[:50]


def main() -> None:
    for raw in sys.stdin:
        line = raw.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
        except json.JSONDecodeError:
            continue
        method = req.get("method")
        req_id = req.get("id")
        params = req.get("params") if isinstance(req.get("params"), dict) else {}

        if method == "initialize":
            version = params.get("protocolVersion", 1)
            reply(
                req_id,
                {
                    "protocolVersion": version,
                    "agentCapabilities": {
                        "loadSession": True,
                        "promptCapabilities": {
                            "image": True,
                            "audio": False,
                            "embeddedContext": True,
                        },
                        "sessionCapabilities": {
                            "list": {},
                        },
                    },
                    "agentInfo": {
                        "name": "minimax-clutch-acp",
                        "version": "0.3.0",
                        "profile": ENGINE_PROFILE,
                    },
                    "authMethods": [],
                },
            )
        elif method == "authenticate":
            reply(req_id, {})
        elif method == "session/list":
            reply(req_id, {"sessions": list_dsh_sessions()})
        elif method == "session/new":
            sess_id = str(uuid.uuid4())
            cwd = params.get("cwd") if isinstance(params.get("cwd"), str) else os.getcwd()
            mcp_servers = params.get("mcpServers") if isinstance(params.get("mcpServers"), list) else []
            patch_file = _write_temp_mcp_patch(mcp_servers) if mcp_servers else None
            sessions[sess_id] = {
                "cwd": cwd,
                "sessionId": sess_id,
                "patchFile": patch_file,
            }
            reply(req_id, {"sessionId": sess_id, "modes": modes_block()})
        elif method == "session/load":
            sess_id = str(params.get("sessionId") or uuid.uuid4())
            cwd = params.get("cwd") if isinstance(params.get("cwd"), str) else os.getcwd()
            sessions[sess_id] = {"cwd": cwd, "sessionId": sess_id}
            reply(req_id, {"sessionId": sess_id, "modes": modes_block()})
        elif method == "session/prompt":
            sess_id = str(params.get("sessionId") or "")
            record = sessions.setdefault(sess_id, {"cwd": os.getcwd(), "sessionId": sess_id})
            cwd = str(record.get("cwd") or os.getcwd())
            text = extract_prompt_text(params.get("prompt"), cwd=cwd)
            if not text:
                fail(req_id, "empty prompt")
                continue
            target_session_id = str(record.get("sessionId") or sess_id)
            thread = threading.Thread(
                target=handle_prompt,
                args=(req_id, target_session_id, text, cwd),
                daemon=True,
            )
            thread.start()
        elif method == "session/cancel":
            sess_id = str(params.get("sessionId") or "")
            cancelled = cancel_session(sess_id)
            if req_id is not None:
                reply(req_id, {"cancelled": cancelled})
        elif method == "ping":
            reply(req_id, {})
        elif req_id is not None:
            reply(req_id, {})


if __name__ == "__main__":
    if "--version" in sys.argv:
        print("minimax-acp 0.3.0 (dsh coding path)")
        sys.exit(0)
    main()
